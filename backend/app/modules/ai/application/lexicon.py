def flatten(table: _IntentTable) -> tuple[str, ...]:
    """Une os termos de todos os idiomas, preservando a ordem e sem duplicatas."""
    return tuple(dict.fromkeys(term for terms in table.values() for term in terms))


def _fold(value: str) -> str:
    normalized = unicodedata.normalize("NFKD", value.casefold())
    return "".join(char for char in normalized if not unicodedata.combining(char))


def _is_non_latin(term: str) -> bool:
    for char in term:
        code = ord(char)
        if (
            0x0400 <= code <= 0x04FF
            or 0x0600 <= code <= 0x06FF
            or 0x0750 <= code <= 0x077F
            or 0x3040 <= code <= 0x30FF
            or 0x3400 <= code <= 0x4DBF
            or 0x4E00 <= code <= 0x9FFF
            or 0x1100 <= code <= 0x11FF
            or 0x3130 <= code <= 0x318F
            or 0xAC00 <= code <= 0xD7AF
        ):
            return True
    return False


def term_present(text: str, term: str) -> bool:
    """Presenca do termo: fronteira de palavra em latim; substring em outros scripts."""
    if _is_non_latin(term):
        return term.casefold() in unicodedata.normalize("NFKC", text).casefold()
    folded_text = _fold(text)
    folded_term = _fold(term)
    if not folded_term:
        return False
    return re.search(rf"(?<!\w){re.escape(folded_term)}(?!\w)", folded_text) is not None


def matches_any(text: str, terms: Sequence[str]) -> bool:
    return any(term_present(text, term) for term in terms)


def find_task(message: str) -> ConsultingTask | None:
    """Primeira tarefa canonica reconhecida (independente do idioma)."""
    for task, table in TASK_TERMS.items():
        if matches_any(message, flatten(table)):
            return task
    return None


def task_terms(task: ConsultingTask) -> tuple[str, ...]:
    return flatten(TASK_TERMS[task])


def query_noise_terms() -> tuple[str, ...]:
    return flatten(QUERY_NOISE)


def minimum_order_question(message: str) -> bool:
    return matches_any(message, flatten(MINIMUM_ORDER_TERMS))
